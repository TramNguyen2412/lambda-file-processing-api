#!/usr/bin/env node
/**
 * scripts/test-local.mjs
 * Comprehensive local test suite (no AWS needed):
 *   1. Excel Generation (500 rows)
 *   2. Excel Parsing and data integrity verification
 *   3. Multipart/form-data extraction helper
 *   4. Synthetic chunked stream simulation (verifies O(1) RAM streaming & byte count)
 *
 * Run: npm run test:local
 */

import { createRequire } from 'module';
import { writeFileSync, mkdirSync } from 'fs';
import { resolve, dirname } from 'path';
import { fileURLToPath } from 'url';
import { Writable } from 'stream';

const require = createRequire(import.meta.url);
const __dirname = dirname(fileURLToPath(import.meta.url));
const distDir = resolve(__dirname, '..', 'dist');

let generator, parser, multipart;
try {
  generator = require(`${distDir}/utils/excelGenerator`);
  parser    = require(`${distDir}/utils/excelParser`);
  multipart = require(`${distDir}/utils/multipartParser`);
} catch (e) {
  console.error('Could not load dist/. Run `npm run build` first.');
  console.error(e.message);
  process.exit(1);
}

async function run() {
  console.log('======================================================');
  console.log('LOCAL TEST SUITE (Node.js 24 + TypeScript)');
  console.log('======================================================\n');

  // -- 1. Excel Generation ----------------------------------------------------
  console.log('1. Testing Excel generation (500 rows)...');
  const genResult = await generator.generateExcel(500);
  console.log(`   - Generated bytes : ${genResult.fileSizeBytes} (${genResult.fileSizeMB} MB)`);
  console.log(`   - Elapsed time    : ${genResult.elapsedMs} ms`);
  console.log(`   - Row count       : ${genResult.rowCount}`);

  const outDir = resolve(__dirname, '..', 'test-files', 'generated');
  mkdirSync(outDir, { recursive: true });
  const outPath = resolve(outDir, 'local-test-500rows.xlsx');
  writeFileSync(outPath, genResult.buffer);
  console.log(`   - Saved sample to : ${outPath}`);
  console.log('   Generation passed\n');

  // -- 2. Excel Parsing -------------------------------------------------------
  console.log('2. Testing Excel parsing from generated buffer...');
  const parseResult = await parser.parseExcel(genResult.buffer);
  console.log(`   - Sheet name   : "${parseResult.sheetName}"`);
  console.log(`   - Row count    : ${parseResult.rowCount} data rows`);
  console.log(`   - Column count : ${parseResult.columnCount}`);
  console.log(`   - Preview rows : ${parseResult.previewRows.length} rows loaded`);

  if (parseResult.rowCount !== 500) {
    throw new Error(`Row count mismatch: expected 500, got ${parseResult.rowCount}`);
  }
  if (parseResult.sheetName !== 'Report') {
    throw new Error(`Sheet name mismatch: expected "Report", got "${parseResult.sheetName}"`);
  }
  console.log('   Parsing integrity passed\n');

  // -- 3. Multipart Extraction Helper -----------------------------------------
  console.log('3. Testing multipart/form-data extraction helper...');

  // 3a. Raw ZIP pass-through
  const rawPassed = multipart.extractFileBuffer(genResult.buffer, 'application/octet-stream');
  if (rawPassed.byteLength !== genResult.buffer.byteLength) {
    throw new Error('Raw binary extraction failed to preserve buffer length');
  }
  console.log('   3a. Raw binary pass-through verified');

  // 3b. Multipart wrapped buffer
  const boundary = '----WebKitFormBoundaryXYZ123';
  const prefix = Buffer.from(
    `--${boundary}\r\nContent-Disposition: form-data; name="file"; filename="report.xlsx"\r\nContent-Type: application/vnd.openxmlformats-officedocument.spreadsheetml.sheet\r\n\r\n`
  );
  const suffix = Buffer.from(`\r\n--${boundary}--\r\n`);
  const multipartBuffer = Buffer.concat([prefix, genResult.buffer, suffix]);

  const extracted = multipart.extractFileBuffer(
    multipartBuffer,
    `multipart/form-data; boundary=${boundary}`
  );

  if (extracted.byteLength !== genResult.buffer.byteLength) {
    throw new Error(
      `Multipart extraction size mismatch: expected ${genResult.buffer.byteLength}, got ${extracted.byteLength}`
    );
  }
  // Verify extracted file parses cleanly as Excel
  const multipartParsed = await parser.parseExcel(extracted);
  if (multipartParsed.rowCount !== 500) {
    throw new Error('Extracted multipart Excel failed parse validation');
  }
  console.log('   3b. Multipart extraction and parse verified\n');

  // -- 4. Synthetic Chunked Streaming Simulation ------------------------------
  console.log('4. Testing synthetic chunked stream simulation (1 MB target, 64 KB chunks)...');
  const targetMB = 1;
  const targetBytes = targetMB * 1024 * 1024;
  const chunkBytes = 64 * 1024;

  let totalReceivedBytes = 0;
  let chunkCount = 0;
  const streamStartTime = Date.now();
  let firstChunkTime = 0;

  // Mock writable destination stream
  const mockDestination = new Writable({
    write(chunk, encoding, callback) {
      if (chunkCount === 0) {
        firstChunkTime = Date.now() - streamStartTime;
      }
      totalReceivedBytes += chunk.length;
      chunkCount++;
      callback();
    },
  });

  // Reusable chunk buffer (O(1) memory)
  const reusableChunk = Buffer.alloc(chunkBytes);
  for (let i = 0; i < chunkBytes; i++) {
    reusableChunk[i] = (i * 31) & 0xff;
  }

  let bytesStreamed = 0;
  while (bytesStreamed < targetBytes) {
    const remaining = targetBytes - bytesStreamed;
    const toWrite = Math.min(chunkBytes, remaining);
    mockDestination.write(toWrite === chunkBytes ? reusableChunk : reusableChunk.subarray(0, toWrite));
    bytesStreamed += toWrite;
  }
  mockDestination.end();

  if (totalReceivedBytes !== targetBytes) {
    throw new Error(`Streamed bytes mismatch: expected ${targetBytes}, got ${totalReceivedBytes}`);
  }
  console.log(`   - Chunks streamed : ${chunkCount}`);
  console.log(`   - Total bytes     : ${totalReceivedBytes} bytes (${(totalReceivedBytes / 1024 / 1024).toFixed(2)} MB)`);
  console.log(`   - Simulated TTFB  : ${firstChunkTime} ms`);
  console.log('   Synthetic chunked streaming verified\n');

  console.log('======================================================');
  console.log('ALL LOCAL TESTS PASSED SUCCESSFULLY!');
  console.log('======================================================\n');
}

run().catch((err) => {
  console.error('\nLocal test failed:', err);
  process.exit(1);
});
